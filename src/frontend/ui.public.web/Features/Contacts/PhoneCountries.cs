/// <summary>
/// Страна в селекторе телефона формы заявки.
/// </summary>
/// <param name="Iso">Код ISO 3166-1 alpha-2 в нижнем регистре: он же id флага в спрайте (flag-ru).</param>
/// <param name="Code">Телефонный код без «+» (у России и Казахстана он общий — «7»).</param>
/// <param name="Trunk">Внутренняя приставка («8» в России, «0» в Европе): маска её отбрасывает, если номер и без неё длиннее нужного.</param>
/// <param name="Length">Сколько цифр в национальном номере — по нему маска режет лишнее и строит плейсхолдер.</param>
/// <param name="Groups">Разбивка национального номера: размеры групп и разделители между ними, например «3 3-2-2» → «900 000-00-00».</param>
/// <param name="NameRu">Название на русском.</param>
/// <param name="NameEn">Название на английском.</param>
/// <param name="NameZh">Название на китайском.</param>
public sealed record PhoneCountry(
    string Iso,
    string Code,
    string Trunk,
    int Length,
    string Groups,
    string NameRu,
    string NameEn,
    string NameZh)
{
    /// <summary>Название страны на языке интерфейса.</summary>
    public string Name => CultureInfo.CurrentUICulture.TwoLetterISOLanguageName switch
    {
        "en" => NameEn,
        "zh" => NameZh,
        _ => NameRu,
    };
}

